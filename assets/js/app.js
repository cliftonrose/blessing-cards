/* ============================================================
   Blessing Cards — presentation & motion
   ============================================================ */
(function () {
  'use strict';

  var DATA = window.BLESSINGS || [];
  if (!DATA.length) return;

  var hasAnime = typeof window.anime === 'function';
  var reduced = window.matchMedia('(prefers-reduced-motion: reduce)').matches;
  var animated = hasAnime && !reduced;

  /* Ambient hue per theme — the room changes colour with the blessing. */
  var THEMES = {
    identity:  { h: 42,  s: 62 },
    hope:      { h: 268, s: 46 },
    strength:  { h: 24,  s: 64 },
    peace:     { h: 196, s: 48 },
    love:      { h: 348, s: 50 },
    provision: { h: 140, s: 38 },
    guidance:  { h: 222, s: 52 },
    joy:       { h: 50,  s: 70 }
  };

  var el = {
    root:        document.documentElement,
    card:        document.getElementById('card'),
    tilt:        document.getElementById('tilt'),
    sheen:       document.getElementById('sheen'),
    seal:        document.getElementById('seal'),
    eyebrow:     document.getElementById('eyebrow'),
    affirmation: document.getElementById('affirmation'),
    rule:        document.getElementById('rule'),
    verse:       document.getElementById('verse'),
    ref:         document.getElementById('ref'),
    flourish:    document.getElementById('flourish'),
    brand:       document.querySelector('.brand'),
    actions:     document.getElementById('actions'),
    foot:        document.querySelector('#view-blessing .foot'),
    btnNew:      document.getElementById('btn-new'),
    btnShare:    document.getElementById('btn-share'),
    listen:      document.getElementById('listen'),
    listenBar:   document.getElementById('listen-bar'),
    toast:       document.getElementById('toast')
  };

  /* Recordings are pre-generated by scripts/generate-audio.js; the page never
     calls a speech API. The manifest says which blessings actually have a file,
     so the button stays hidden rather than requesting one that 404s. */
  var AUDIO = window.BLESSING_AUDIO || { dir: 'assets/audio/', ext: '.mp3', ids: [] };
  var HAS_AUDIO = {};
  (AUDIO.ids || []).forEach(function (id) { HAS_AUDIO[id] = true; });

  var current = null;
  var busy = false;
  var fontsReady = false;   /* webfonts have settled (or we stopped waiting) */
  var onScreen = false;     /* the deck has this view showing */
  var revealed = false;
  /* Flipped false if requestAnimationFrame turns out not to run (see rafAlive). */
  var motionLive = animated;
  var hue = { h: 42, s: 62 };

  /* ---------- helpers ---------- */

  function esc(s) {
    return String(s).replace(/[&<>"']/g, function (c) {
      return { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c];
    });
  }

  /* Each word gets a clipping wrapper so it can rise out of a mask. */
  function maskedWords(text) {
    return text.split(/\s+/).map(function (w) {
      return '<span class="w"><span class="wi">' + esc(w) + '</span></span>';
    }).join(' ');
  }

  function plainWords(text) {
    return text.split(/\s+/).map(function (w) {
      return '<span class="w">' + esc(w) + '</span>';
    }).join(' ');
  }

  function delay(ms) {
    return new Promise(function (r) { setTimeout(r, ms); });
  }

  /* Backstop: if a reveal hasn't finished in time, force the finished state. */
  function withWatchdog(promise, ms) {
    var settled = false;
    function mark() { settled = true; }
    promise.then(mark, mark);
    setTimeout(function () {
      if (settled) return;
      showInstant();
      busy = false;
      el.btnNew.disabled = false;
    }, ms);
    return promise;
  }

  /* ---------- selection ---------- */

  function dayIndex() {
    var n = new Date();
    var days = Math.floor(Date.UTC(n.getFullYear(), n.getMonth(), n.getDate()) / 86400000);
    return ((days % DATA.length) + DATA.length) % DATA.length;
  }

  function randomOther(previous) {
    if (DATA.length === 1) return DATA[0];
    var pick;
    do { pick = DATA[Math.floor(Math.random() * DATA.length)]; }
    while (previous && pick.id === previous.id);
    return pick;
  }

  /* ?b=<id> pins one blessing (one QR per card design).
     ?daily  gives everyone the same blessing for the calendar day. */
  function fromQuery() {
    var p = new URLSearchParams(window.location.search);
    var id = p.get('b') || p.get('id');
    if (id) {
      var found = DATA.filter(function (x) { return x.id === id; })[0];
      if (found) return { blessing: found, label: 'A blessing for you' };
    }
    if (p.has('daily')) {
      return { blessing: DATA[dayIndex()], label: 'Today’s blessing' };
    }
    return null;
  }

  /* ---------- render ---------- */

  function render(b, label) {
    current = b;
    el.eyebrow.textContent = label || 'A blessing for you';
    el.affirmation.innerHTML = maskedWords(b.affirmation);
    el.verse.innerHTML = plainWords(b.verse);
    el.ref.textContent = b.ref;
    el.card.setAttribute('data-theme', b.theme);
    syncListen(b);
  }

  function setAura(theme, duration) {
    var t = THEMES[theme] || THEMES.identity;
    if (!motionLive || !duration) {
      hue.h = t.h; hue.s = t.s;
      applyAura();
      return;
    }
    /* Take the short way round the colour wheel. */
    var target = t.h;
    if (Math.abs(target - hue.h) > 180) target += (hue.h > target ? 360 : -360);
    window.anime({
      targets: hue,
      h: target,
      s: t.s,
      duration: duration,
      easing: 'easeInOutQuad',
      update: applyAura,
      complete: function () { hue.h = ((t.h % 360) + 360) % 360; }
    });
  }

  function applyAura() {
    el.root.style.setProperty('--aura-h', (((hue.h % 360) + 360) % 360).toFixed(1));
    el.root.style.setProperty('--aura-s', hue.s.toFixed(1) + '%');
  }

  /* ---------- fixed card height ---------- */

  /* Measure every blessing in an offscreen copy of the card and hold the real
     one at the tallest. Done by measurement rather than a hard-coded height
     because the longest passage wraps to a different number of lines at every
     width. Re-run on resize and once webfonts have settled, since both change
     the answer. */
  /* Measured on the real card rather than a detached copy. A copy parked on the
     body lays out in a different context and came back about 15px short, which
     left the page overflowing by exactly that much. Every blessing is swapped
     through, measured and put back inside one task, so the browser never paints
     an intermediate state and none of it is visible. */
  function tallestCard() {
    if (!el.card.getBoundingClientRect().width) return 0;

    var keptAff = el.affirmation.innerHTML;
    var keptVerse = el.verse.innerHTML;
    var keptMin = el.card.style.minHeight;
    var keptHidden = el.listen.hidden;

    el.card.style.minHeight = '0px';
    /* Reserve room for the button even on blessings that lack a recording, so
       the height never depends on which files happen to exist. */
    el.listen.hidden = false;

    var max = 0;
    for (var i = 0; i < DATA.length; i++) {
      el.affirmation.innerHTML = maskedWords(DATA[i].affirmation);
      el.verse.innerHTML = plainWords(DATA[i].verse);
      var h = el.card.offsetHeight;
      if (h > max) max = h;
    }

    el.affirmation.innerHTML = keptAff;
    el.verse.innerHTML = keptVerse;
    el.listen.hidden = keptHidden;
    el.card.style.minHeight = keptMin;

    return max;
  }

  var fittedWidth = 0;
  var fittedHeight = 0;

  /* How much vertical room is left for the card once the brand, controls,
     footer, padding and gaps have taken their share. Summed explicitly rather
     than derived from the shell, whose min-height of 100svh would overstate the
     furniture whenever the content is shorter than the screen. */
  function roomForCard() {
    var shell = document.querySelector('.shell');
    var stage = document.querySelector('.stage');
    if (!shell || !stage) return 0;

    var view = document.getElementById('view-blessing');
    var nav = document.getElementById('deck-nav');
    var s = getComputedStyle(shell);
    var chrome =
      parseFloat(s.paddingTop) + parseFloat(s.paddingBottom) +
      /* shell: brand -> deck -> nav */
      (parseFloat(s.rowGap) || 0) * 2 +
      /* view: stage -> footer */
      (view ? (parseFloat(getComputedStyle(view).rowGap) || 0) : 0) +
      (parseFloat(getComputedStyle(stage).rowGap) || 0) +
      el.brand.offsetHeight +
      el.actions.offsetHeight +
      el.foot.offsetHeight +
      (nav ? nav.offsetHeight : 0);

    return window.innerHeight - chrome - 8; /* a hair of breathing room */
  }

  /* Shrink the card's vertical rhythm only as far as it takes to keep the
     controls on screen. Below this the type stops being comfortable, and
     scrolling is the better trade. */
  var MIN_CARD_SCALE = 0.8;

  function setCardScale(v) {
    el.root.style.setProperty('--card-scale', String(v));
  }

  /* Only refit when the width or viewport height actually changes. That makes
     this cheap to call often, and stops the height we set from retriggering the
     observer below. */
  function fitCard() {
    var w = Math.round(el.card.getBoundingClientRect().width);
    var vh = window.innerHeight;
    if (!w) return;
    if (w === fittedWidth && Math.abs(vh - fittedHeight) < 40) return;

    setCardScale(1);
    el.card.style.minHeight = '';

    var room = roomForCard();
    var tallest = tallestCard();
    if (!tallest) return;

    /* Full size if it already fits. Otherwise bisect for the largest scale that
       does. Stepping down proportionally overshoots badly — shrinking type by 2%
       can drop a whole line of wrap, cutting far more height than asked for — so
       searching keeps the type as large as the space genuinely allows. */
    if (room > 0 && tallest > room) {
      var lo = MIN_CARD_SCALE;
      var hi = 1;
      var best = 0;
      var bestHeight = 0;

      for (var i = 0; i < 6; i++) {
        var mid = (lo + hi) / 2;
        setCardScale(mid);
        var h = tallestCard();
        if (h <= room) {
          best = mid;
          bestHeight = h;
          lo = mid;
        } else {
          hi = mid;
        }
      }

      if (best) {
        setCardScale(best);
        tallest = bestHeight;
      } else {
        /* Even the floor does not fit; take it and let the page scroll. */
        setCardScale(MIN_CARD_SCALE);
        tallest = tallestCard();
      }
    }

    el.card.style.minHeight = tallest + 'px';

    /* Everything above works from measurements of a detached copy, and those
       can land a little under what the live card actually renders. Rather than
       trust the arithmetic, check the page it produced and give back a little
       more until nothing hangs below the fold. */
    var scaleNow = parseFloat(el.root.style.getPropertyValue('--card-scale')) || 1;
    for (var pass = 0; pass < 4; pass++) {
      var over = document.documentElement.scrollHeight - window.innerHeight;
      if (over <= 0 || scaleNow <= MIN_CARD_SCALE) break;

      scaleNow = Math.max(MIN_CARD_SCALE, scaleNow - 0.03);
      setCardScale(scaleNow);
      el.card.style.minHeight = '';
      var settled = tallestCard();
      if (!settled) break;
      el.card.style.minHeight = settled + 'px';
    }

    fittedWidth = w;
    fittedHeight = vh;
  }

  /* The card can have no width yet when boot runs — a hidden tab, or layout
     deferred for any other reason — and measuring then yields nothing. Watching
     the element means we fit as soon as it has a real size, and again whenever
     that size changes, instead of relying on one well-timed call. */
  function watchCardWidth() {
    fitCard();

    var refit;
    var later = function () {
      clearTimeout(refit);
      refit = setTimeout(fitCard, 180);
    };

    if (typeof ResizeObserver === 'function') {
      new ResizeObserver(later).observe(el.card);
    }

    /* Viewport height changes on its own when a mobile URL bar shows or hides,
       which the card observer never sees. */
    window.addEventListener('resize', later);
    if (window.visualViewport) window.visualViewport.addEventListener('resize', later);
  }

  /* ---------- motion ---------- */

  function showInstant() {
    /* Drop any in-flight animation so a late tick can't undo this. */
    if (hasAnime) {
      window.anime.remove([
        el.card, el.eyebrow, el.ref, el.rule, el.flourish, el.sheen,
        el.brand, el.actions, el.foot, el.listen
      ]);
      window.anime.remove('#affirmation .wi');
      window.anime.remove('#verse .w');
      window.anime.remove('#seal circle, #seal path');
    }

    [el.card, el.eyebrow, el.ref, el.brand, el.actions, el.foot].forEach(function (n) {
      n.style.opacity = 1;
      n.style.transform = 'none';
    });
    el.sheen.style.opacity = 0;
    el.rule.style.transform = 'scaleX(1)';
    Array.prototype.forEach.call(
      el.card.querySelectorAll('.wi, .w'),
      function (n) { n.style.opacity = 1; n.style.transform = 'none'; }
    );
    Array.prototype.forEach.call(
      el.card.querySelectorAll('#seal path, #seal circle, #flourish path, #flourish circle'),
      function (n) { n.style.strokeDasharray = 'none'; n.style.strokeDashoffset = 0; n.style.opacity = 1; }
    );
    el.flourish.style.opacity = 1;
    el.listen.style.opacity = 1;
    el.seal.style.opacity = 1;
  }

  /* Puts the changing text back to its pre-reveal position. The card, seal and
     flourish are deliberately untouched. */
  function resetContent() {
    var anime = window.anime;
    anime.set('#affirmation .wi', { translateY: '115%' });
    anime.set('#verse .w', { opacity: 0, translateY: 12 });
    anime.set([el.eyebrow, el.ref, el.listen], { opacity: 0 });
    anime.set(el.rule, { scaleX: 0 });
  }

  /* Content only — used every time a new blessing is drawn. */
  function revealContent(tl, offset) {
    var anime = window.anime;

    tl.add({
      targets: el.eyebrow,
      opacity: [0, 1],
      translateY: [10, 0],
      duration: 800
    }, offset);

    tl.add({
      targets: '#affirmation .wi',
      translateY: ['115%', '0%'],
      duration: 1050,
      delay: anime.stagger(52)
    }, '-=620');

    tl.add({
      targets: el.rule,
      scaleX: [0, 1],
      duration: 950,
      easing: 'easeInOutQuart'
    }, '-=780');

    tl.add({
      targets: '#verse .w',
      opacity: [0, 1],
      translateY: [12, 0],
      duration: 780,
      delay: anime.stagger(19)
    }, '-=800');

    tl.add({
      targets: el.ref,
      opacity: [0, 1],
      letterSpacing: ['0.62em', '0.22em'],
      duration: 1000
    }, '-=560');

    tl.add({
      targets: el.listen,
      opacity: [0, 1],
      duration: 900
    }, '-=780');

    return tl;
  }

  /* First paint only: the whole card arrives, the seal draws itself, and light
     passes over the paper. None of this repeats on later draws. */
  function revealCard() {
    var anime = window.anime;

    anime.set(el.card, { opacity: 0, translateY: 30, scale: 0.94, rotateX: 8 });
    anime.set(el.flourish, { opacity: 0 });
    anime.set(el.sheen, { opacity: 0, translateX: '-140%', skewX: -18 });
    resetContent();

    var tl = anime.timeline({ easing: 'easeOutExpo' });

    tl.add({
      targets: el.card,
      opacity: [0, 1],
      translateY: [30, 0],
      scale: [0.94, 1],
      rotateX: [8, 0],
      duration: 1300
    });

    tl.add({
      targets: '#seal circle, #seal path',
      strokeDashoffset: [anime.setDashoffset, 0],
      opacity: [0, 1],
      duration: 1100,
      delay: anime.stagger(55),
      easing: 'easeInOutSine'
    }, '-=1050');

    revealContent(tl, '-=750');

    tl.add({
      targets: el.flourish,
      opacity: [0, 1],
      duration: 900
    }, '-=900');

    tl.add({
      targets: el.sheen,
      opacity: [0, 0.9],
      translateX: ['-140%', '-30%'],
      duration: 450,
      easing: 'linear'
    }, '-=700');

    tl.add({
      targets: el.sheen,
      translateX: ['-30%', '250%'],
      opacity: [0.9, 0],
      duration: 1050,
      easing: 'easeInQuad'
    });

    return tl.finished;
  }

  function swapInContent() {
    resetContent();
    var tl = window.anime.timeline({ easing: 'easeOutExpo' });
    revealContent(tl, 0);
    return tl.finished;
  }

  function dismissCard() {
    var anime = window.anime;
    var tl = anime.timeline({ easing: 'easeInQuad' });

    tl.add({
      targets: '#affirmation .wi',
      translateY: ['0%', '-115%'],
      duration: 480,
      delay: anime.stagger(24)
    });

    tl.add({
      targets: '#verse .w',
      opacity: 0,
      translateY: -10,
      duration: 340,
      delay: anime.stagger(8)
    }, '-=420');

    tl.add({
      targets: [el.eyebrow, el.ref, el.listen],
      opacity: 0,
      duration: 320
    }, '-=340');

    tl.add({
      targets: el.rule,
      scaleX: 0,
      duration: 380,
      easing: 'easeInOutQuart'
    }, '-=320');

    /* The card itself, the seal and the flourish stay exactly where they are —
       only the words leave, so drawing again reads as the text changing rather
       than the page reloading. */
    return tl.finished;
  }

  /* ---------- listen ---------- */

  var listenPlayer = null;

  function hasAudio(b) { return !!(b && HAS_AUDIO[b.id]); }

  function audioUrl(b) { return AUDIO.dir + b.id + AUDIO.ext; }

  function initListen() {
    if (!el.listen) return;
    listenPlayer = window.createListenPlayer({
      button: el.listen,
      bar: el.listenBar,
      toast: toast,
      playLabel: 'Listen to this blessing',
      pauseLabel: 'Pause this blessing'
    });
    el.listen.addEventListener('click', toggleListen);
  }

  function toggleListen() {
    if (!listenPlayer || !current || !hasAudio(current)) return;
    listenPlayer.toggle(audioUrl(current), current.id);
  }

  function stopAudio() {
    if (listenPlayer) listenPlayer.stop();
  }

  function syncListen(b) {
    if (!el.listen) return;
    el.listen.hidden = !hasAudio(b);
  }

  /* ---------- interaction ---------- */

  function drawNext() {
    if (busy) return;
    busy = true;
    stopAudio();
    el.btnNew.disabled = true;

    var next = randomOther(current);

    if (!motionLive) {
      render(next);
      setAura(next.theme, 0);
      showInstant();
      busy = false;
      el.btnNew.disabled = false;
      return;
    }

    setAura(next.theme, 1400);

    var run = dismissCard().then(function () {
      render(next);
      return swapInContent();
    }).then(function () {
      busy = false;
      el.btnNew.disabled = false;
    });

    run.catch(function () {
      showInstant();
      busy = false;
      el.btnNew.disabled = false;
    });

    withWatchdog(run, 6000);
  }

  function shareText() {
    return current.affirmation + '\n\n“' + current.verse + '”\n— ' + current.ref;
  }

  function shareUrl() {
    var u = new URL(window.location.href);
    u.search = '';
    u.hash = '';
    u.searchParams.set('b', current.id);
    return u.toString();
  }

  function toast(msg) {
    el.toast.textContent = msg;
    el.toast.classList.add('is-visible');
    clearTimeout(toast._t);
    toast._t = setTimeout(function () {
      el.toast.classList.remove('is-visible');
    }, 2600);
  }

  function onShare() {
    var payload = {
      title: 'A blessing for you',
      text: shareText(),
      url: shareUrl()
    };

    if (navigator.share) {
      navigator.share(payload).catch(function (err) {
        if (err && err.name === 'AbortError') return;
        copyFallback();
      });
      return;
    }
    copyFallback();
  }

  function copyFallback() {
    var text = shareText() + '\n\n' + shareUrl();
    if (navigator.clipboard && navigator.clipboard.writeText) {
      navigator.clipboard.writeText(text)
        .then(function () { toast('Blessing copied'); })
        .catch(function () { toast('Copy not available'); });
    } else {
      toast('Copy not available');
    }
  }

  /* ---------- pointer parallax ---------- */

  function initTilt() {
    if (!window.matchMedia('(pointer: fine)').matches) return;
    var target = { x: 0, y: 0 };
    var at = { x: 0, y: 0 };
    var raf = null;

    function loop() {
      at.x += (target.x - at.x) * 0.07;
      at.y += (target.y - at.y) * 0.07;
      el.tilt.style.transform = 'rotateY(' + at.x.toFixed(3) + 'deg) rotateX(' + at.y.toFixed(3) + 'deg)';
      if (Math.abs(target.x - at.x) < 0.01 && Math.abs(target.y - at.y) < 0.01) {
        raf = null;
        return;
      }
      raf = requestAnimationFrame(loop);
    }

    window.addEventListener('pointermove', function (e) {
      target.x = (e.clientX / window.innerWidth - 0.5) * 2 * 6;
      target.y = -(e.clientY / window.innerHeight - 0.5) * 2 * 4.5;
      if (raf === null) raf = requestAnimationFrame(loop);
    }, { passive: true });

    window.addEventListener('pointerleave', function () {
      target.x = 0; target.y = 0;
      if (raf === null) raf = requestAnimationFrame(loop);
    }, { passive: true });
  }

  /* ---------- boot ---------- */

  function chromeIn() {
    if (!animated) return;
    window.anime({
      targets: [el.brand, el.actions, el.foot],
      opacity: [0, 1],
      translateY: [12, 0],
      duration: 1100,
      delay: window.anime.stagger(140, { start: 500 }),
      easing: 'easeOutExpo'
    });
  }

  /* The first measurement can land before the serif does, and the card is then
     held at the fallback's smaller height for good. document.fonts.ready is not
     enough on its own — it resolves early when nothing happens to be loading at
     the moment it is asked — so the timers are what this actually leans on. They
     fire whether or not the frame loop is running, which the font events and the
     resize observer do not. */
  function watchFonts() {
    var refit = function () {
      fittedWidth = 0;
      fitCard();
    };

    if (document.fonts) {
      if (document.fonts.ready) document.fonts.ready.then(refit);
      if (document.fonts.addEventListener) {
        document.fonts.addEventListener('loadingdone', refit);
      }
    }
    setTimeout(refit, 1800);
    setTimeout(refit, 4000);
  }

  function boot() {
    /* A scan should always land at the top of the card, never on a restored
       scroll position from a previous visit. */
    if ('scrollRestoration' in history) history.scrollRestoration = 'manual';

    var q = fromQuery();
    var start = q ? q.blessing : randomOther(null);

    render(start, q && q.label);
    setAura(start.theme, 0);

    initListen();
    watchFonts();
    el.btnNew.addEventListener('click', drawNext);
    el.btnShare.addEventListener('click', onShare);

    document.addEventListener('keydown', function (e) {
      if (e.target && /^(INPUT|TEXTAREA)$/.test(e.target.tagName)) return;
      if (e.key === 'ArrowRight' || e.key === 'n' || e.key === 'N') {
        e.preventDefault();
        drawNext();
      }
    });

    if (!animated) {
      watchCardWidth();
      showInstant();
      revealed = true;
      return;
    }

    Ambient.rafAlive(600).then(function (alive) {
      if (!alive) {
        motionLive = false;
        watchCardWidth();
        showInstant();
        revealed = true;
        return;
      }

      Ambient.motes(document.getElementById('motes'));
      initTilt();
      watchCardWidth();


      /* Hold the reveal until the serif has loaded, so words don't reflow
         mid-animation — but never wait longer than 1.4s for it. */
      var fonts = (document.fonts && document.fonts.ready)
        ? Promise.race([document.fonts.ready, delay(1400)])
        : delay(0);

      fonts.then(function () {
        fontsReady = true;
        maybeReveal();
      });
    });
  }

  /* The card assembles the first time it is actually looked at. Someone landing
     on ?gospel=true and swiping across still sees it build, rather than finding
     it already sitting there because the timeline played to an empty room. */
  function maybeReveal() {
    if (revealed || !fontsReady || !onScreen) return;
    revealed = true;

    /* Remeasure once webfonts land: metrics shift, and so does the answer. */
    fittedWidth = 0;
    fitCard();
    chromeIn();

    var run = revealCard();
    run.catch(showInstant);
    withWatchdog(run, 8000);
  }

  window.BlessingView = {
    activate: function () {
      onScreen = true;
      /* Width goes from zero to real when the view is shown, so remeasure. */
      fitCard();
      setAura(current ? current.theme : 'identity', 0);
      maybeReveal();
    },
    deactivate: function () {
      stopAudio();
    }
  };

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', boot);
  } else {
    boot();
  }
})();
